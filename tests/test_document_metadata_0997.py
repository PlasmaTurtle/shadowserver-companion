"""Document properties describe this export, never the bundled Word template."""

from datetime import datetime, timezone
from zipfile import ZipFile
from xml.etree import ElementTree as ET

from docx import Document
import pytest

from test_reports_040 import specimen
from workbench.print_policy import set_document_properties
from workbench.report_renderers import render_docx

NS = {
    "dc": "http://purl.org/dc/elements/1.1/",
    "dcterms": "http://purl.org/dc/terms/",
    "cp": "http://schemas.openxmlformats.org/package/2006/metadata/core-properties",
}


def test_export_properties_use_snapshot_time_and_report_revision(tmp_path):
    data = specimen()
    data["created_at"] = "2026-11-12T22:48:05-05:00"
    data["report_revision"] = 3
    target = tmp_path / "notification.docx"
    render_docx(data, target, tmp_path)
    with ZipFile(target) as archive:
        raw = archive.read("docProps/core.xml")
        properties = ET.fromstring(raw)
    assert properties.findtext("dcterms:created", namespaces=NS) == "2026-11-13T03:48:05Z"
    assert properties.findtext("dcterms:modified", namespaces=NS) == "2026-11-13T03:48:05Z"
    assert properties.findtext("cp:revision", namespaces=NS) == "3"
    assert properties.findtext("dc:creator", namespaces=NS) == data["draft"]["sender_name"]
    assert properties.findtext("dc:title", namespaces=NS) == data["draft"]["subject"]
    assert b"2013-" not in raw and b"generated by python-docx" not in raw
    assert properties.findtext("cp:keywords", namespaces=NS) in ("", None)


@pytest.mark.parametrize("timestamp", [None, "", "not a date", "2026-11-12", "2026-11-12T12:00:00"])
def test_unknown_export_time_is_absent_instead_of_invented(timestamp):
    doc = Document()
    doc.core_properties.last_printed = datetime(2000, 1, 1, tzinfo=timezone.utc)
    set_document_properties(doc, title="Notification", author="Analyst", created_at=timestamp)
    assert doc.core_properties.created is None
    assert doc.core_properties.modified is None
    assert doc.core_properties.last_printed is None
    assert not doc.core_properties.comments
